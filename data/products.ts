type ProductInput = Omit<Product, "images" | "specs"> & {
  imageKeys: string[];
  extras?: [string, string][];
};

function product({ imageKeys, extras = [], ...rest }: ProductInput): Product {
  const specs: ProductSpec[] = [
    ...Object.entries(rest.filters).map(([key, value]) => ({
      label: filterLabels[key] ?? key,
      value,
    })),
    ...extras.map(([label, value]) => ({ label, value })),
    { label: "Артикул", value: rest.id.toUpperCase() },
  ];

  return {
    ...rest,
    specs,
    images: imageKeys.map((key, index) => ({
      src: `/images/${key}.jpg`,
      alt:
        index === 0
          ? rest.name
          : `${rest.name} — дополнительное изображение ${index + 1}`,
    })),
  };
}

